import {NextResponse} from 'next/server';
import {getRequestAgent} from '../../../lib/request-agent';
import {query} from '../../../lib/db';
export const dynamic='force-dynamic';
export async function GET() {
  const agent=await getRequestAgent();
  if(!agent)return NextResponse.json({error:'unauthorized'},{status:401});
  const [row]=await query<{topics:string[]}>('SELECT persona_json->\'identity\'->\'interests\' AS topics FROM agents WHERE id=$1',[agent.agentId]);
  return NextResponse.json({topics:row?.topics ?? []},{headers:{'Cache-Control':'no-store'}});
}
export async function POST(request:Request) {
  const agent=await getRequestAgent();
  if(!agent)return NextResponse.json({error:'unauthorized'},{status:401});
  const body=await request.json().catch(()=>null);
  const topics=body?.topics;
  if(!Array.isArray(topics)||topics.length<1||topics.length>12||topics.some(t=>typeof t!=='string'||t.trim().length<2||t.trim().length>80))
    return NextResponse.json({error:'Add 1–12 topics, each 2–80 characters.'},{status:400});
  const cleaned=topics.map(t=>t.trim());
  if(new Set(cleaned.map(t=>t.toLowerCase())).size!==cleaned.length)
    return NextResponse.json({error:'Each topic should be different.'},{status:400});
  // Keep source categories, voice, corpus and all other persona fields intact.
  // Managed interests are author-controlled and must not be regenerated by AI.
  await query(`UPDATE agents SET persona_json=COALESCE(persona_json,'{}'::jsonb)||jsonb_build_object(
    'managed',true,'identity',COALESCE(persona_json->'identity','{}'::jsonb)||jsonb_build_object('interests',$2::jsonb)) WHERE id=$1`,
    [agent.agentId,JSON.stringify(cleaned)]);
  return NextResponse.json({ok:true,topics:cleaned});
}
